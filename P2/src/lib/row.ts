import type { City } from '../types'

// ДАНО, готове — не змінюйте. Формат рядка стрічки, той самий, що картка P1.
// Живе поза App.tsx, бо це чиста функція: місто на вході, рядок на виході,
// жодного стану. У власній верстці CityCard він не обов'язковий — але, як і
// будь-яка чиста функція, не заважає.

export function rowOf(city: City): string {
  return `${city.name} · ${city.country} · ${city.temperature}°`
}

// ДАНО, готове — не змінюйте. Ключ рядка стрічки: його підставляють у
// keyExtractor списку. Ключ — id міста, а не індекс масиву: FlatList
// рециклить рядки, і з ключем-індексом під швидким скролом вони
// перескакують на чужі дані [P2 · L2 слайди 5, 17].

export function keyOf(city: City): string {
  return city.id
}
